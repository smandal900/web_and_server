// Prints docs/server-todo.md: every endpoint the web app calls that the server does not fully have yet.
// Run with `npm run server-todo` (Node strips the TypeScript types itself, no build step needed).
import { writeFileSync } from 'node:fs';
import { allEndpoints } from '../src/api/endpoints.ts';

const all = allEndpoints();
const missing = all.filter((e) => e.support === 'todo');
const stubs = all.filter((e) => e.support === 'stub');
const ok = all.filter((e) => e.support === 'ok');

const table = (rows: typeof all) =>
  ['| Method | Path | Used as |', '|---|---|---|', ...rows.map((e) => `| \`${e.method}\` | \`/api${e.path}\` | \`${e.name}\` |`)].join('\n');

const text = `# Server to-do (generated)

Generated by \`npm run server-todo\` from \`web/src/api/endpoints.ts\`. Do not edit by hand:
change the \`ok(...)\` / \`stub(...)\` / \`todo(...)\` markers in that file as the server grows, then run the script again.

- **${ok.length}** endpoints work today
- **${stubs.length}** endpoints answer with an empty or static result (a "stub")
- **${missing.length}** endpoints do not exist yet (the web calls them and shows "not supported yet")

## Not implemented (${missing.length})

${table(missing)}

## Stubs: answer, but with empty/static data (${stubs.length})

${table(stubs)}

## Implemented (${ok.length})

${table(ok)}
`;

writeFileSync(new URL('../docs/server-todo.md', import.meta.url), text);
console.log(`docs/server-todo.md written: ${ok.length} ok, ${stubs.length} stub, ${missing.length} missing`);
